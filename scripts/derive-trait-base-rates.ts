// Derives the per-source CoreTag base rates used by app/lib/traitInformation.ts.
//   npx -y tsx scripts/derive-trait-base-rates.ts > /tmp/rates.txt
// P(source s supports trait t) over deterministic synthetic inputs (uniform UI input space, like
// diagnostic-identity-diversity.ts). Not a population estimate — it measures how often each source's
// own mapping emits a trait, which is what makes a trait common or rare as evidence.
// mbti / blood-type are exact (all types enumerated); saju / western-astrology are sampled.
import { analyzeDestiny, TAROT_DATA, type CoreTag } from '../app/lib/analysis';
import { traitSupportInConvergenceScope } from '../app/lib/analysisPatterns';
import { PALM_TRAIT_VOCAB } from '../app/lib/palmReading';
import { LOCATION_OPTION_GROUPS } from '../app/lib/regions';

const N = 6000;
const SIJU = ['00:30', '02:30', '04:30', '06:30', '08:30', '10:30', '12:30', '14:30', '16:30', '18:30', '20:30', '22:30'];
const MBTI = ['INTJ', 'INTP', 'ENTJ', 'ENTP', 'INFJ', 'INFP', 'ENFJ', 'ENFP', 'ISTJ', 'ISFJ', 'ESTJ', 'ESFJ', 'ISTP', 'ISFP', 'ESTP', 'ESFP'];
const PLACES = LOCATION_OPTION_GROUPS.flatMap((g) => g.options);
let seed = 4242;
const rnd = () => ((seed = (seed * 1103515245 + 12345) % 2147483648) / 2147483648);
const pick = <T,>(a: readonly T[]) => a[Math.floor(rnd() * a.length)];

const hits: Record<string, Map<CoreTag, number>> = {};
const totals: Record<string, number> = {};
const note = (source: string, traits: Iterable<CoreTag>) => {
  totals[source] = (totals[source] ?? 0) + 1;
  hits[source] ??= new Map();
  for (const t of traits) hits[source].set(t, (hits[source].get(t) ?? 0) + 1);
};

for (let i = 0; i < N; i++) {
  const y = 1955 + Math.floor(rnd() * 55), m = 1 + Math.floor(rnd() * 12), d = 1 + Math.floor(rnd() * 28);
  const time = rnd() < 0.7 ? pick(SIJU) : '';
  const place = time ? pick(PLACES) : undefined;
  const s = analyzeDestiny(`${y}-${String(m).padStart(2, '0')}-${String(d).padStart(2, '0')}`, time, pick(MBTI), 'female', pick(['A', 'B', 'O', 'AB']),
    TAROT_DATA[0], place?.lat, place?.lon, 'solar', false);
  const support = traitSupportInConvergenceScope(s.trace!);
  for (const source of ['saju', 'western-astrology', 'mbti', 'blood-type']) {
    note(source, [...support.entries()].filter(([, v]) => v.sources.includes(source)).map(([t]) => t));
  }
}

const vocab = PALM_TRAIT_VOCAB as readonly CoreTag[];
console.log('// generated by scripts/derive-trait-base-rates.ts (N=' + N + ')');
for (const source of Object.keys(hits)) {
  const row = vocab.map((t) => `${t}: ${((hits[source].get(t) ?? 0) / totals[source]).toFixed(3)}`).join(', ');
  console.log(`  '${source}': { ${row} },`);
}
